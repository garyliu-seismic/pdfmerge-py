"""Font-file catalogue: font-map loading and PDF-font -> font-file matching.

Mirrors CTS2.0 (C#):
  * ``FontMapItem`` / ``FontMapUtility``  - font map = JSON file ``{"files":[{path,names,styles,...}]}``
    (generated by ``FontMapGenerator``) or the text form ``Name|path;Name|path``.
  * ``PdfOtfFontProcessor.__GetRelation`` - PostScript-name match first, then
    family + style heuristics (Regular / Bold / Italic / BoldItalic).

Differences from the C#:
  * name/style data is read from the font file itself with fontTools (MIT); the JSON
    ``names`` / ``styles`` only add aliases.
  * the style parser also understands ``Family-Style`` / ``FamilyStyleMT`` PDF names, not only ``Family,Style``.
  * ``strict`` mode disables the "Bold -> Regular" style fallback that the C# applies silently.
"""

from __future__ import annotations

import json
import re
import warnings
from dataclasses import dataclass, field
from pathlib import Path

from fontTools.ttLib import TTCollection, TTFont, TTLibError

FONT_EXTS = {".ttf", ".otf", ".ttc", ".otc", ".pfb"}


def norm(s: str) -> str:
    """Case/space/punctuation-insensitive key."""
    return re.sub(r"[^a-z0-9]", "", s.lower())


def strip_subset_prefix(name: str) -> str:
    return re.sub(r"^[A-Z]{6}\+", "", name.lstrip("/"))


@dataclass
class FontFileInfo:
    path: Path
    kind: str                      # 'truetype' (glyf) | 'cff' | 'type1'
    ps_name: str
    family: str
    style: str
    full_name: str = ""
    bold: bool = False
    italic: bool = False
    fs_type: int | None = None
    cff_cid_keyed: bool = False
    font_number: int | None = None  # face index inside a .ttc
    aliases: set[str] = field(default_factory=set)       # normalised exact-name aliases
    family_aliases: set[str] = field(default_factory=set)  # normalised family aliases

    def describe(self) -> str:
        n = f"#{self.font_number}" if self.font_number is not None else ""
        return f"{self.ps_name} ({self.family} / {self.style}) [{self.path.name}{n}]"

    @property
    def metadata_key(self) -> tuple:
        return (norm(self.ps_name), norm(self.family), norm(self.style), self.kind)

    @property
    def restricted_license(self) -> bool:
        """OS/2 fsType 'Restricted License embedding' (bit 1) - must not be embedded."""
        return bool(self.fs_type is not None and (self.fs_type & 0x0002))


def _name(font: TTFont, *ids: int) -> str:
    table = font["name"]
    for i in ids:
        rec = table.getName(i, 3, 1, 0x409) or table.getName(i, 1, 0, 0) or table.getName(i, 3, 1)
        if rec is None:
            rec = next((r for r in table.names if r.nameID == i), None)
        if rec is not None:
            try:
                s = rec.toUnicode().strip()
            except Exception:
                continue
            if s:
                return s
    return ""


def _info_from_ttfont(font: TTFont, path: Path, number: int | None) -> FontFileInfo:
    if "CFF2" in font:
        raise ValueError("CFF2 (variable CFF) fonts are not supported")
    if "glyf" in font:
        kind = "truetype"
    elif "CFF " in font:
        kind = "cff"
    else:
        raise ValueError("no glyf or CFF table")
    ps = _name(font, 6)
    family = _name(font, 16, 1)
    style = _name(font, 17, 2) or "Regular"
    full = _name(font, 4)
    bold = italic = False
    if "OS/2" in font:
        sel = font["OS/2"].fsSelection
        italic = bool(sel & 1)
        bold = bool(sel & 32)
    if "head" in font:
        mac = font["head"].macStyle
        bold = bold or bool(mac & 1)
        italic = italic or bool(mac & 2)
    if not ps:
        ps = norm(family) + "-" + norm(style)
    cid_keyed = False
    if kind == "cff":
        top = font["CFF "].cff.topDictIndex[0]
        cid_keyed = hasattr(top, "ROS")
    fs_type = font["OS/2"].fsType if "OS/2" in font else None
    info = FontFileInfo(path=path, kind=kind, ps_name=ps, family=family, style=style, full_name=full,
                        bold=bold, italic=italic, fs_type=fs_type, cff_cid_keyed=cid_keyed,
                        font_number=number)
    info.aliases = {norm(x) for x in (ps, full) if x}
    info.family_aliases = {norm(family)} if family else set()
    return info


def _info_from_pfb(path: Path) -> FontFileInfo:
    data = path.read_bytes()[:8192]
    txt = data.decode("latin-1")

    def g(key: str) -> str:
        m = re.search(r"/" + key + r"\s*\(([^)]*)\)", txt)
        return m.group(1).strip() if m else ""

    m = re.search(r"/FontName\s*/(\S+)", txt)
    ps = m.group(1) if m else path.stem
    family = g("FamilyName") or ps.split("-")[0]
    full = g("FullName")
    weight = g("Weight")
    style = "Bold" if weight.lower() in ("bold", "black", "heavy") else "Regular"
    ia = re.search(r"/ItalicAngle\s+(-?[\d.]+)", txt)
    italic = bool(ia and float(ia.group(1)) != 0)
    if italic:
        style = "BoldItalic" if style == "Bold" else "Italic"
    info = FontFileInfo(path=path, kind="type1", ps_name=ps, family=family, style=style, full_name=full,
                        bold="Bold" in style, italic=italic)
    info.aliases = {norm(x) for x in (ps, full) if x}
    info.family_aliases = {norm(family)}
    return info


def read_font_file(path: Path, extra_names: list[str] | None = None) -> list[FontFileInfo]:
    """Read one font file (a .ttc yields one entry per face). Raises ValueError if unreadable."""
    path = Path(path)
    ext = path.suffix.lower()
    out: list[FontFileInfo] = []
    try:
        if ext == ".pfb":
            out.append(_info_from_pfb(path))
        elif ext in (".ttc", ".otc"):
            coll = TTCollection(str(path), lazy=True)
            for i, f in enumerate(coll.fonts):
                try:
                    out.append(_info_from_ttfont(f, path, i))
                except ValueError:
                    continue
        else:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                f = TTFont(str(path), lazy=True)
                out.append(_info_from_ttfont(f, path, None))
                f.close()
    except (TTLibError, OSError, KeyError, AttributeError, struct_error) as ex:
        raise ValueError(f"cannot read font '{path}': {ex}") from ex
    if not out:
        raise ValueError(f"no usable face in '{path}'")
    for info in out:
        for n in extra_names or []:
            info.aliases.add(norm(n))
            info.family_aliases.add(norm(n))
    return out


try:  # struct.error may be raised for truncated tables
    from struct import error as struct_error
except ImportError:  # pragma: no cover
    struct_error = ValueError


class FontCatalog:
    """The set of candidate font files, with the C# matching heuristics."""

    def __init__(self) -> None:
        self.fonts: list[FontFileInfo] = []
        self.warnings: list[str] = []
        self._seen_keys: set[tuple] = set()

    # -- loading ------------------------------------------------------
    def add_file(self, path: Path, names: list[str] | None = None, styles: str = "") -> int:
        try:
            infos = read_font_file(path, names)
        except ValueError as ex:
            self.warnings.append(str(ex))
            return 0
        n = 0
        for info in infos:
            key = info.metadata_key
            if key in self._seen_keys:  # C#: duplicates (same metadata) are skipped
                self.warnings.append(f"duplicate font skipped: {info.describe()}")
                continue
            self._seen_keys.add(key)
            self.fonts.append(info)
            n += 1
        return n

    def add_font_map_json(self, json_path: Path) -> int:
        """Load a ``font-map.json`` (C# ``InsFontMap``); paths are relative to the JSON's directory."""
        json_path = Path(json_path)
        data = json.loads(json_path.read_text(encoding="utf-8-sig"))
        base = json_path.parent
        n = 0
        for entry in data.get("files", []):
            p = Path(entry.get("path", ""))
            if not p.is_absolute():
                p = base / p
            if not p.exists():
                self.warnings.append(f"font map entry not found: {p}")
                continue
            n += self.add_file(p, list(entry.get("names") or []), entry.get("styles", ""))
        return n

    def add_font_map_text(self, text: str, relative_dir: Path | None = None) -> int:
        """C# text form: ``Name|path;Name|path`` (separators ';' or newline). A path to a .json is loaded as a map."""
        n = 0
        for item in re.split(r"\s*[\n;]\s*", text.strip()):
            if not item:
                continue
            name, _, path = item.partition("|") if "|" in item else ("", "", item)
            p = Path(path)
            if not p.is_absolute() and relative_dir is not None:
                p = relative_dir / p
            if not p.exists():
                self.warnings.append(f"font map item not found: {p}")
                continue
            if p.suffix.lower() == ".json":
                n += self.add_font_map_json(p)
            else:
                n += self.add_file(p, [name] if name else None)
        return n

    def add_font_map(self, arg: str) -> int:
        p = Path(arg)
        if p.exists() and p.suffix.lower() == ".json":
            return self.add_font_map_json(p)
        return self.add_font_map_text(arg, None)

    def add_directory(self, directory: Path, recursive: bool = True) -> int:
        """Use ``font-map.json`` in the directory when present (as the C# does), else scan font files."""
        directory = Path(directory)
        if not directory.is_dir():
            raise FileNotFoundError(f"font directory not found: {directory}")
        fm = directory / "font-map.json"
        if fm.exists():
            return self.add_font_map_json(fm)
        n = 0
        it = directory.rglob("*") if recursive else directory.glob("*")
        for p in sorted(it):
            if p.is_file() and p.suffix.lower() in FONT_EXTS:
                n += self.add_file(p)
        return n

    def add_named(self, spec: str) -> int:
        """``NAME=path`` : use the font file for PDF fonts called NAME (PostScript or family name)."""
        name, sep, path = spec.partition("=")
        if not sep or not name or not path:
            raise ValueError(f"--font expects NAME=path, got '{spec}'")
        before = len(self.fonts)
        added = self.add_file(Path(path), [name])
        if added == 0:
            # duplicate of an already known font: still attach the alias
            for info in read_font_file(Path(path), [name]):
                for f in self.fonts:
                    if f.metadata_key == info.metadata_key:
                        f.aliases.add(norm(name))
                        f.family_aliases.add(norm(name))
                        return 1
            raise ValueError(f"cannot use font '{path}' (see warnings)")
        return len(self.fonts) - before

    # -- matching -----------------------------------------------------
    def match(self, pdf_font_name: str, strict: bool = False) -> tuple[FontFileInfo | None, str]:
        """Return (font, how). ``how`` is 'postscript' | 'family-style' | 'family-style-fallback' | ''."""
        name = strip_subset_prefix(pdf_font_name)
        if not name:
            return None, ""
        n = norm(name)
        for f in self.fonts:  # 1. PostScript / full name / explicit alias
            if n in f.aliases:
                return f, "postscript"

        splits = _candidate_splits(name)
        for i, (family, style) in enumerate(splits):
            f, exact = self._by_family_style(family, style)
            if f is not None:
                # the family-only reading of a name that carries style info is itself a fallback
                primary = bool(style) or i == 0 or len(splits) == 1
                if exact and primary:
                    return f, "family-style"
                if not strict:
                    return f, "family-style-fallback"
        return None, ""

    def _by_family_style(self, family: str, style: str):
        """Port of __GetRelation family branches. Returns (font, is_exact)."""
        fam = norm(family)
        cands = [f for f in self.fonts if fam and (fam in f.family_aliases or fam == norm(f.family))]
        if not cands:
            return None, False
        bold, italic, extra = parse_style(style)

        def fstyle(f: FontFileInfo) -> str:
            s = norm(f.style)
            return "italic" if s in ("regitalic", "regularitalic") else s

        def first(pred):
            return next((f for f in cands if pred(f)), None)

        def is_regular(f):
            return fstyle(f) in ("regular", "reg", "", "normal", "roman", "book")

        if extra:  # weights such as Light / Semibold / Condensed: only an exact style hit is acceptable
            hit = first(lambda f: fstyle(f) == norm(style) or fstyle(f) == extra + ("bold" if bold else "") + ("italic" if italic else ""))
            return (hit, True) if hit else (None, False)
        if not bold and not italic:
            hit = first(is_regular)
            if hit:
                return hit, True
            hit = first(lambda f: not f.bold and not f.italic)
            if hit:
                return hit, True
            hit = cands[0]
            return hit, False
        if bold and not italic:
            hit = (first(lambda f: fstyle(f) == "bold")
                   or first(lambda f: f.bold and not f.italic)
                   or first(lambda f: "bold" in fstyle(f) and "italic" not in fstyle(f)))
            if hit:
                return hit, True
        elif italic and not bold:
            hit = (first(lambda f: fstyle(f) in ("italic", "oblique"))
                   or first(lambda f: f.italic and not f.bold)
                   or first(lambda f: "italic" in fstyle(f) and "bold" not in fstyle(f)))
            if hit:
                return hit, True
        else:
            hit = (first(lambda f: fstyle(f) in ("bolditalic", "boldoblique"))
                   or first(lambda f: f.bold and f.italic))
            if hit:
                return hit, True
        # C#: "Use Regular style instead"
        reg, _ = self._by_family_style(family, "")
        return (reg, False) if reg is not None else (None, False)


_STYLE_TOKENS = re.compile(r"(bold|italic|oblique|ital|bd|it|regular|reg|roman|normal|mt|ps)")


def parse_style(style: str) -> tuple[bool, bool, str]:
    """Return (bold, italic, leftover) for a style string such as 'BoldItalic' / 'Bold Oblique' / 'Light'."""
    s = norm(style)
    bold = italic = False
    rest = s
    # greedy token consumption
    out = ""
    i = 0
    while i < len(rest):
        m = _STYLE_TOKENS.match(rest, i)
        if m:
            t = m.group(1)
            if t in ("bold", "bd"):
                bold = True
            elif t in ("italic", "oblique", "ital", "it"):
                italic = True
            i = m.end()
        else:
            out += rest[i]
            i += 1
    return bold, italic, out


def _candidate_splits(name: str) -> list[tuple[str, str]]:
    """Possible (family, style) readings of a PDF BaseFont name, most explicit first."""
    cands: list[tuple[str, str]] = []
    if "," in name:  # C# form: Family,Style
        fam, _, sty = name.partition(",")
        cands.append((fam, sty))
    if "-" in name:
        fam, _, sty = name.rpartition("-")
        cands.append((fam, sty))
    # glued: ArialBold, TimesNewRomanBoldItalicMT
    m = re.match(r"^(.*?)((?:Bold|Italic|Oblique|BoldItalic|BoldOblique)+)(?:MT|PS)?$", name)
    if m and m.group(1):
        cands.append((m.group(1), m.group(2)))
    base = name.split(",")[0].split("-")[0]
    cands.append((base, ""))
    # ArialMT / TimesNewRomanPS : strip the vendor suffix
    out: list[tuple[str, str]] = []
    for fam, sty in cands:
        out.append((fam, sty))
        f2 = re.sub(r"(MT|PS)$", "", fam)
        if f2 != fam and f2:
            out.append((f2, sty))
    seen = set()
    uniq = []
    for c in out:
        k = (norm(c[0]), norm(c[1]))
        if k not in seen:
            seen.add(k)
            uniq.append(c)
    return uniq
